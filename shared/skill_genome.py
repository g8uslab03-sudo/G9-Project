def build_skill_catalog() -> Dict[str, SkillGene]:
    """Build the full 250-skill gene catalog."""
    catalog: Dict[str, SkillGene] = {}
    category_order = [
        SkillCategory.DATA_SENSING,
        SkillCategory.COGNITIVE_REASONING,
        SkillCategory.CONTENT_GENERATION,
        SkillCategory.SYSTEM_EXECUTION,
        SkillCategory.GOVERNANCE_SECURITY,
    ]
    index = 0
    for category in category_order:
        for _ in range(50):
            if index >= len(_SKILL_ENTRIES):
                break
            entry = _SKILL_ENTRIES[index]
            index += 1
            code = entry["code"]
            skill = SkillGene(
                code=code,
                name=entry["name"],
                category=category,
                description=entry["description"],
                open_source_url=entry["url"],
                download_command=entry["download"],
                dependencies=entry.get("deps", []),
                network_required=entry.get("network", False),
                gpu_required=False,
                sandbox_required=True,
            )
            catalog[code] = skill
    return catalog


SKILL_CATALOG: Dict[str, SkillGene] = build_skill_catalog()


def get_skill(code: str) -> SkillGene:
    if code not in SKILL_CATALOG:
        raise KeyError(f"Skill code not found: {code}")
    return SKILL_CATALOG[code]


def list_skills_by_category(category: SkillCategory) -> List[SkillGene]:
    return [s for s in SKILL_CATALOG.values() if s.category == category]


def search_skills(query: str) -> List[SkillGene]:
    q = query.lower()
    return [s for s in SKILL_CATALOG.values() if q in s.code.lower() or q in s.name.lower() or q in s.description.lower()]
